"""Strive's icons: bundle.css's masks as Compose vectors.

Run `python3 docs/design/15-tokens/icons.py` after bundle.css's icons change. It reads every
`.ic-<name> { --i: url("data:image/svg+xml,…"); }` mask there and writes the app's Icons.kt,
one ImageVector per mask in bundle.css's order. It stops on any SVG feature it does not
translate, naming the icon. CI runs it and fails if Icons.kt changed.
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import unquote

BUNDLE = Path(__file__).parents[1] / "18-approved/system/project/components/bundle.css"
KOTLIN = Path(__file__).parents[3] / "shared/src/commonMain/kotlin/se/carlsmeister/strive/theme/Icons.kt"

MASK = re.compile(r'\.ic-([a-z0-9-]+) \{ --i: url\("data:image/svg\+xml,([^"]*)"\); \}')
SVG = re.compile(r"<svg ([^>]*)>(.*)</svg>")
ATTR = re.compile(r"([\w:-]+)='([^']*)'")
FILLED = {"xmlns": "http://www.w3.org/2000/svg", "viewBox": "0 0 24 24", "fill": "black"}
STROKED = {"xmlns": "http://www.w3.org/2000/svg", "viewBox": "0 0 24 24", "fill": "none", "stroke": "black",
           "stroke-width": "2", "stroke-linecap": "round", "stroke-linejoin": "round"}
PATH_DATA = re.compile(r"[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]*")


def circle(cx, cy, r):
    return f"M{cx - r:g} {cy:g}a{r:g} {r:g} 0 1 0 {2 * r:g} 0a{r:g} {r:g} 0 1 0 {-2 * r:g} 0z"


def rect(x, y, width, height, rx):
    rx = min(rx, width / 2, height / 2)
    h, v = width - 2 * rx, height - 2 * rx
    a = f"a{rx:g} {rx:g} 0 0 1"
    return (f"M{x + rx:g} {y:g}h{h:g}{a} {rx:g} {rx:g}v{v:g}{a} {-rx:g} {rx:g}"
            f"h{-h:g}{a} {-rx:g} {-rx:g}v{-v:g}{a} {rx:g} {-rx:g}z")


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def elements(name, markup):
    """The icon's elements as one path string; anything else stops the script."""
    out = []
    for e in ET.fromstring(f"<g>{markup}</g>"):
        a = e.attrib
        if len(e) or (e.text or "").strip() or (e.tail or "").strip():
            raise SystemExit(f"{name}: <{e.tag}> has content icons.py does not translate")
        if e.tag == "path" and out and a.get("d", "").startswith("m"):
            # Joined into one path, a relative m would start from the previous element's end, not from 0 0.
            raise SystemExit(f"{name}: a <path> after the first starts with a relative m; write it as M")
        if e.tag == "path" and a.keys() == {"d"} and PATH_DATA.fullmatch(a["d"]):
            out.append(a["d"])
        elif e.tag == "circle" and a.keys() == {"cx", "cy", "r"}:
            out.append(circle(*(float(a[k]) for k in ("cx", "cy", "r"))))
        elif e.tag == "rect" and a.keys() in ({"x", "y", "width", "height"}, {"x", "y", "width", "height", "rx"}):
            out.append(rect(*(float(a.get(k, 0)) for k in ("x", "y", "width", "height", "rx"))))
        else:
            raise SystemExit(f"{name}: <{e.tag} {' '.join(f'{k}={v!r}' for k, v in a.items())}> is not a path, circle or rect icons.py translates")
    return "".join(out)


def icon(name, svg):
    """(filled, path) for one mask; a root other than the two the Icons card draws stops the script."""
    match = SVG.fullmatch(svg)
    if not match:
        raise SystemExit(f"{name}: not one <svg> element: {svg[:80]}")
    root = dict(ATTR.findall(match[1]))
    if ATTR.sub("", match[1]).strip() or root not in (FILLED, STROKED):
        raise SystemExit(f"{name}: root <svg {match[1]}> is neither fill='black' nor a 2 pt round black stroke on 0 0 24 24")
    return root == FILLED, elements(name, match[2])


def icons():
    css = BUNDLE.read_text()
    found = [(name, *icon(name, unquote(svg))) for name, svg in MASK.findall(css)]
    if len(found) != css.count("--i: url("):
        raise SystemExit("a --i mask in bundle.css is not written as `.ic-<name> { --i: url(\"data:image/svg+xml,…\"); }`")
    return found


def kotlin(found):
    out = [
        "// Generated from docs/design/18-approved/system/project/components/bundle.css by docs/design/15-tokens/icons.py.",
        "// Change the masks there and run it; do not edit this file.",
        "package se.carlsmeister.strive.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.PathParser",
        "import androidx.compose.ui.unit.dp",
        "",
        f"/** The system's {len(found)} icons, one per mask in bundle.css, in its order. Each draws in black, which `Icon`'s tint replaces. */",
        "internal object StriveIcons {",
    ]
    out += [f'    val {pascal(n)}: ImageVector by lazy {{ icon("{n}", {str(f).lower()}, "{p}") }}' for n, f, p in found]
    out += [
        "",
        "    /** Every icon with its CSS name, in bundle.css's order. */",
        "    val all: List<Pair<String, ImageVector>> by lazy {",
        "        listOf(",
        *(f'            "{n}" to {pascal(n)},' for n, _, _ in found),
        "        )",
        "    }",
        "}",
        "",
        "private fun icon(name: String, filled: Boolean, path: String): ImageVector =",
        "    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).addPath(",
        "        PathParser().parsePathString(path).toNodes(),",
        "        fill = if (filled) SolidColor(Color.Black) else null,",
        "        stroke = if (filled) null else SolidColor(Color.Black),",
        "        strokeLineWidth = 2f,",
        "        strokeLineCap = StrokeCap.Round,",
        "        strokeLineJoin = StrokeJoin.Round,",
        "    ).build()",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    assert circle(12, 12, 4) == "M8 12a4 4 0 1 0 8 0a4 4 0 1 0 -8 0z"
    assert rect(3, 5, 18, 16, 2) == "M5 5h14a2 2 0 0 1 2 2v12a2 2 0 0 1 -2 2h-14a2 2 0 0 1 -2 -2v-12a2 2 0 0 1 2 -2z"
    assert pascal("chev-r") == "ChevR" and pascal("x") == "X"
    try:
        elements("dot", "<line x1='1' y1='1' x2='2' y2='2'/>")
        raise AssertionError("an unknown element must stop the script")
    except SystemExit as stop:
        assert "dot" in str(stop) and "line" in str(stop)
    assert elements("chev-r", "<path d='m9 6 6 6-6 6'/>") == "m9 6 6 6-6 6"
    try:
        elements("skip", "<path d='M18 5v14'/><path d='m5 5 9 7'/>")
        raise AssertionError("a relative m after the first element must stop the script")
    except SystemExit as stop:
        assert "skip" in str(stop)
    found = icons()
    names = [pascal(n) for n, _, _ in found]
    assert len(set(names)) == len(names) and all(n.isidentifier() and not n[0].isdigit() for n in names), names
    KOTLIN.write_text(kotlin(found))
    print(f"wrote {len(found)} icons")
